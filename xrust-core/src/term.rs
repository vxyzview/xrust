    #[test]
    fn no_panic_on_garbage_fuzz() {
        let mut t = term();
        // Deterministic pseudo-random garbage incl. partial escapes.
        let mut x: u32 = 0x9E3779B9;
        let mut data = Vec::new();
        for _ in 0..20000 {
            x ^= x << 13;
            x ^= x >> 17;
            x ^= x << 5;
            data.push(x as u8);
            if x % 7 == 0 {
                data.push(0x1B);
            }
        }
        t.feed(&data);
        assert_eq!(t.grid().cells.len(), 20 * 6);
    }
