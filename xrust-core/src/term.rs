//! The `Terminal` actor: owns grid(s), scrollback, modes, and implements the
//! [`vte::Perform`] callbacks. Produces a binary snapshot for the UI and a
//! response buffer (DA/DSR/color queries) that the session writes back to
//! the PTY.

use crate::color::{Color, Scheme};
use crate::grid::{
    Cell, Grid, PutOutcome, ATTR_BOLD, ATTR_DIM, ATTR_INVISIBLE, ATTR_ITALIC, ATTR_REVERSE,
    ATTR_STRIKE, ATTR_UNDERLINE,
};
use crate::scrollback::Scrollback;
use crate::vte::{Param, Perform};

/// Runtime mode flags (DECSET/DECRST).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct ModeFlags {
    pub app_cursor: bool,           // ?1
    pub app_keypad: bool,           // ?66 / ESC =
    pub origin: bool,               // ?6
    pub autowrap: bool,             // ?7 (default on)
    pub cursor_visible: bool,       // ?25 (default on)
    pub alt_screen: bool,           // ?47 / ?1047 / ?1049
    pub bracketed_paste: bool,      // ?2004
    pub mouse_protocol: u16,        // 0=off, 9=click, 1000=normal, 1002=button, 1003=any
    pub mouse_sgr: bool,            // ?1006
    pub focus_events: bool,         // ?1004
    pub cursor_blink: Option<bool>, // ?12
    pub reverse_video: bool,        // ?5
}

/// Pen state for SGR.
#[derive(Debug, Clone, Default)]
struct Pen {
    fg: Color,
    bg: Color,
    attrs: u16,
}

/// DECSAVE (ESC 7) snapshot.
#[derive(Debug, Clone, Default)]
struct SavedCursor {
    row: usize,
    col: usize,
    pen: Pen,
    origin: bool,
    charset_g: usize,
    wrap_next: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EventKind {
    Title,
    Bell,
    ClipboardSet,
    CwdChanged,
}

#[derive(Debug, Clone)]
pub struct Terminal {
    pub cols: usize,
    pub rows: usize,
    main_grid: Grid,
    alt_grid: Grid,
    pub modes: ModeFlags,
    pub scrollback: Scrollback,
    pen: Pen,
    saved: SavedCursor,
    saved_main: Option<(Vec<Cell>, CursorState)>,
    charset_g0: u8,
    charset_g1: u8,
    charset_shift: usize,
    title: String,
    pub cwd: Option<String>,
    pub pending_responses: Vec<u8>,
    pub bell_count: u32,
    pub clipboard: Option<String>,
    pub seq: u64,
    pub events: Vec<EventKind>,
    /// Color overrides from OSC 4 (index → rgb).
    pub palette_overrides: Vec<(u8, u32)>,
    pub default_fg: Color,
    pub default_bg: Color,
    /// Persistent VTE parser: keeps escape/UTF-8 state across feeds so a
    /// multibyte sequence split across PTY read boundaries is rejoined
    /// instead of dropped (CJK / emoji corruption at 16 KiB read edges).
    vte: crate::vte::Parser,
}

#[derive(Debug, Clone, Default)]
struct CursorState {
    row: usize,
    col: usize,
    wrap_next: bool,
    origin: bool,
    region: Option<(usize, usize)>,
}

impl Terminal {
    pub fn new(cols: usize, rows: usize, scrollback_capacity: usize) -> Self {
        let modes = ModeFlags {
            autowrap: true,
            cursor_visible: true,
            ..ModeFlags::default()
        };
        Terminal {
            cols,
            rows,
            main_grid: Grid::new(cols, rows),
            alt_grid: Grid::new(cols, rows),
            modes,
            scrollback: Scrollback::new(scrollback_capacity),
            pen: Pen::default(),
            saved: SavedCursor::default(),
            saved_main: None,
            charset_g0: b'B',
            charset_g1: b'B',
            charset_shift: 0,
            title: String::new(),
            cwd: None,
            pending_responses: Vec::new(),
            bell_count: 0,
            clipboard: None,
            seq: 0,
            events: Vec::new(),
            palette_overrides: Vec::new(),
            default_fg: Color::Default,
            default_bg: Color::Default,
            vte: crate::vte::Parser::new(),
        }
    }

    pub fn grid(&self) -> &Grid {
        if self.modes.alt_screen {
            &self.alt_grid
        } else {
            &self.main_grid
        }
    }

    fn grid_mut(&mut self) -> &mut Grid {
        if self.modes.alt_screen {
            &mut self.alt_grid
        } else {
            &mut self.main_grid
        }
    }

    /// Feed raw PTY output.
    pub fn feed(&mut self, bytes: &[u8]) {
        // Swap the persistent parser out so `&mut self` (as Perform) can be
        // borrowed while feeding; swap it back afterwards. Carried-over
        // partial escape sequences / UTF-8 tails survive across calls.
        let mut parser = std::mem::take(&mut self.vte);
        parser.feed(bytes, self);
        self.vte = parser;
        self.seq += 1;
    }

    /// Take responses generated by queries (written back to the PTY).
    pub fn take_responses(&mut self) -> Vec<u8> {
        std::mem::take(&mut self.pending_responses)
    }

    pub fn take_events(&mut self) -> Vec<EventKind> {
        std::mem::take(&mut self.events)
    }

    pub fn title(&self) -> &str {
        &self.title
    }

    /// Write text as a paste; bracketed paste is applied when mode 2004 is on.
    pub fn paste(&mut self, text: &str) {
        if self.modes.bracketed_paste {
            self.pending_responses.extend_from_slice(b"\x1b[200~");
            self.pending_responses.extend_from_slice(text.as_bytes());
            self.pending_responses.extend_from_slice(b"\x1b[201~");
        } else {
            self.pending_responses.extend_from_slice(text.as_bytes());
        }
    }

    /// Binary snapshot for the UI:
    /// `[u64 seq][u16 cols][u16 rows][u16 cur_row][u16 cur_col][u8 mode_bits]`
    /// then per cell: `[u32 cp][u8 n_marks]([u32 mark]…)[u32 fg][u32 bg][u16 attrs]`.
    /// `fg`/`bg` = `0xFFFFFFFF` for default.
    pub fn encode_snapshot(&self) -> Vec<u8> {
        let g = self.grid();
        let mut out = Vec::with_capacity(16 + g.cells.len() * 18);
        out.extend_from_slice(&self.seq.to_be_bytes());
        out.extend_from_slice(&(g.cols as u16).to_be_bytes());
        out.extend_from_slice(&(g.rows as u16).to_be_bytes());
        out.extend_from_slice(&(g.cursor.row as u16).to_be_bytes());
        out.extend_from_slice(&(g.cursor.col as u16).to_be_bytes());
        let mut bits = 0u8;
        if self.modes.cursor_visible {
            bits |= 1;
        }
        if self.modes.alt_screen {
            bits |= 2;
        }
        if self.bell_count != 0 {
            bits |= 4;
        }
        out.push(bits);
        for cell in &g.cells {
            out.extend_from_slice(&(cell.ch as u32).to_be_bytes());
            out.push(cell.combining.chars().count() as u8);
            for m in cell.combining.chars() {
                out.extend_from_slice(&(m as u32).to_be_bytes());
            }
            out.extend_from_slice(&enc_color(cell.fg).to_be_bytes());
            out.extend_from_slice(&enc_color(cell.bg).to_be_bytes());
            out.extend_from_slice(&cell.attrs.to_be_bytes());
        }
        out
    }

    /// Resize with history re-flow. Cursor position is best-effort preserved.
    pub fn resize(&mut self, cols: usize, rows: usize) {
        let pairs: Vec<(Vec<Cell>, bool)> = self
            .scrollback
            .iter_with_flags()
            .map(|(c, w)| (c.to_vec(), w))
            .collect();
        let (new_hist, new_flags) = crate::reflow::reflow(&pairs, cols);
        self.scrollback.clear();
        for (line, flag) in new_hist.into_iter().zip(new_flags) {
            self.scrollback.push(line, flag);
        }
        self.main_grid.resize(cols, rows);
        self.alt_grid.resize(cols, rows);
        self.cols = cols;
        self.rows = rows;
        self.seq += 1;
    }

    pub fn set_scrollback_capacity(&mut self, cap: usize) {
        self.scrollback.set_capacity(cap);
    }

    pub fn clear_scrollback(&mut self) {
        self.scrollback.clear();
    }

    /// Scroll offset for the UI: 0 = live, N = N lines up.
    pub fn history_len(&self) -> usize {
        self.scrollback.len()
    }

    /// Resolve the effective text of a history line (absolute ordinal).
    pub fn history_line(&self, ordinal: u64) -> Option<Vec<Cell>> {
        let base = self.scrollback.base_ordinal();
        if ordinal < base {
            return None;
        }
        self.scrollback
            .get((ordinal - base) as usize)
            .map(|l| l.to_vec())
    }

    // ---------- scrolling core ----------

    fn scroll_up_capture(&mut self, n: usize) {
        let full = self.grid().scroll_region.is_none();
        let top = self.grid().region_top();
        let flags: Vec<bool> = (top..(top + n).min(self.grid().rows))
            .map(|r| self.grid().wrapped[r])
            .collect();
        let lines = self.grid_mut().scroll_up(n);
        if full && !self.modes.alt_screen {
            for (line, flag) in lines.into_iter().zip(flags) {
                self.scrollback.push(line, flag);
            }
        }
    }

    fn linefeed(&mut self) {
        let g = self.grid_mut();
        if g.cursor.row == g.region_bottom() {
            // Column is intentionally unchanged (LNM off).
        }
        let at_bottom = self.grid().cursor.row == self.grid().region_bottom();
        if at_bottom {
            self.scroll_up_capture(1);
        } else {
            self.grid_mut().move_down(1);
        }
        self.grid_mut().wrap_next = false;
    }

    // ---------- Perform ----------

    fn print_char(&mut self, ch: char) {
        // Charset mapping (DEC special graphics on G0/G1).
        let active = if self.charset_shift == 0 {
            self.charset_g0
        } else {
            self.charset_g1
        };
        let mapped = if active == b'0' { dec_special(ch) } else { ch };

        loop {
            let outcome = {
                let (fg, bg, attrs, wrap) = (
                    self.pen.fg,
                    self.pen.bg,
                    self.pen.attrs,
                    self.modes.autowrap,
                );
                let g = self.grid_mut();
                g.put_char(mapped, "", fg, bg, attrs, wrap)
            };
            match outcome {
                PutOutcome::None => return,
                PutOutcome::Advanced => {
                    let wrap = self.modes.autowrap;
                    self.grid_mut().advance(wrap);
                    return;
                }
                PutOutcome::RetryAfterScroll => {
                    // Wrap-cause scroll: the pushed row's flag comes from the
                    // grid (the wide char set it).
                    let full = self.grid().scroll_region.is_none();
                    let top = self.grid().region_top();
                    let flag = self.grid().wrapped[top];
                    let mut lines = self.grid_mut().scroll_up(1);
                    if full && !self.modes.alt_screen {
                        self.scrollback.push(lines.remove(0), flag);
                    }
                    let g = self.grid_mut();
                    g.cursor.row = g.region_bottom();
                    g.cursor.col = 0;
                    g.wrap_next = false;
                    // loop and re-put
                }
            }
        }
    }

    fn respond(&mut self, s: &[u8]) {
        self.pending_responses.extend_from_slice(s);
    }
}

fn enc_color(c: Color) -> u32 {
    match c {
        Color::Default => 0xFFFF_FFFF,
        Color::Rgb(v) => v | 0xFF00_0000,
        Color::Indexed(i) => 0x0100_0000 | i as u32,
    }
}

/// DEC Special Graphics mapping (used by ncurses line-drawing).
fn dec_special(c: char) -> char {
    match c {
        '`' => '◆',
        'a' => '▒',
        'b' => '␉',
        'c' => '␌',
        'd' => '␍',
        'e' => '␊',
        'f' => '°',
        'g' => '±',
        'h' => '␤',
        'i' => '␋',
        'j' => '┘',
        'k' => '┐',
        'l' => '┌',
        'm' => '└',
        'n' => '┼',
        'o' => '⎺',
        'p' => '⎻',
        'q' => '─',
        'r' => '⎼',
        's' => '⎽',
        't' => '├',
        'u' => '┤',
        'v' => '┴',
        'w' => '┬',
        'x' => '│',
        'y' => '≤',
        'z' => '≥',
        '{' => 'π',
        '|' => '≠',
        '}' => '£',
        '~' => '·',
        other => other,
    }
}

fn param_or(params: &[Param], i: usize, def: u16) -> u16 {
    params.get(i).map(|p| p.value).unwrap_or(def)
}

impl Perform for Terminal {
    fn print(&mut self, ch: char) {
        self.print_char(ch);
    }

    fn execute(&mut self, b: u8) {
        match b {
            0x07 => {
                self.bell_count += 1;
                self.events.push(EventKind::Bell);
            }
            0x08 => self.grid_mut().move_left(1),  // BS
            0x09 => self.grid_mut().tab_forward(), // HT
            0x0A..=0x0C => self.linefeed(),
            0x0D => {
                let g = self.grid_mut();
                g.cursor.col = 0;
                g.wrap_next = false;
            }
            0x0E => self.charset_shift = 1, // SO
            0x0F => self.charset_shift = 0, // SI
            _ => {}
        }
    }

    fn csi_dispatch(
        &mut self,
        params: &[Param],
        intermediates: &[u8],
        final_byte: u8,
        private: bool,
    ) {
        let n = |i: usize, d: u16| -> usize { param_or(params, i, d).max(1) as usize };
        match (private, intermediates.first(), final_byte) {
            // CUU/CUD/CUF/CUB
            (false, None, b'A') => self.grid_mut().move_up(n(0, 1)),
            (false, None, b'B') => self.grid_mut().move_down(n(0, 1)),
            (false, None, b'C') => self.grid_mut().move_right(n(0, 1)),
            (false, None, b'D') => self.grid_mut().move_left(n(0, 1)),
            // CNL/CPL
            (false, None, b'E') => {
                self.grid_mut().move_down(n(0, 1));
                self.grid_mut().cursor.col = 0;
            }
            (false, None, b'F') => {
                self.grid_mut().move_up(n(0, 1));
                self.grid_mut().cursor.col = 0;
            }
            // CHA / HPA
            (false, None, b'G') | (false, None, b'`') => {
                let c = param_or(params, 0, 1).max(1) as usize - 1;
                self.grid_mut().cursor.col = c.min(self.cols - 1);
                self.grid_mut().wrap_next = false;
            }
            // VPA
            (false, None, b'd') => {
                let r = param_or(params, 0, 1).max(1) as usize - 1;
                let g = self.grid_mut();
                let base = g.region_top();
                g.cursor.row = if g.origin_mode {
                    base + r.min(g.rows - 1 - base)
                } else {
                    r.min(g.rows - 1)
                };
                g.wrap_next = false;
            }
            // CUP/HVP
            (false, None, b'H') | (false, None, b'f') => {
                let r = param_or(params, 0, 1).max(1) as usize - 1;
                let c = param_or(params, 1, 1).max(1) as usize - 1;
                let g = self.grid_mut();
                if g.origin_mode {
                    let top = g.region_top();
                    let bottom = g.region_bottom();
                    g.cursor.row = (top + r).min(bottom);
                } else {
                    g.cursor.row = r.min(g.rows - 1);
                }
                g.cursor.col = c.min(g.cols - 1);
                g.wrap_next = false;
            }
            // ED
            (false, None, b'J') => match param_or(params, 0, 0) {
                3 => {
                    self.clear_scrollback();
                    self.grid_mut().erase_display(2);
                }
                m => self.grid_mut().erase_display(m as u8),
            },
            // EL
            (false, None, b'K') => self.grid_mut().erase_line(param_or(params, 0, 0) as u8),
            // IL / DL
            (false, None, b'L') => self.grid_mut().insert_lines(n(0, 1)),
            (false, None, b'M') => self.grid_mut().delete_lines(n(0, 1)),
            // ICH / DCH / ECH
            (false, None, b'@') => self.grid_mut().insert_cells(n(0, 1)),
            (false, None, b'P') => self.grid_mut().delete_cells(n(0, 1)),
            (false, None, b'X') => {
                let cnt = n(0, 1);
                let (r, c) = (self.grid().cursor.row, self.grid().cursor.col);
                let g = self.grid_mut();
                let end = (c + cnt).min(g.cols);
                let cols = g.cols;
                let row = &mut g.cells[r * cols..(r + 1) * cols];
                for cell in &mut row[c..end] {
                    *cell = Cell::default();
                }
            }
            // SU / SD
            (false, None, b'S') => self.scroll_up_capture(n(0, 1)),
            (false, None, b'T') => {
                let cnt = n(0, 1);
                self.grid_mut().scroll_down(cnt);
            }
            // REP
            (false, None, b'b') => {
                if let Some(ch) = self.grid().last_printed {
                    for _ in 0..n(0, 1) {
                        self.print_char(ch);
                    }
                }
            }
            // DA1 / DSR
            (false, None, b'c') => {
                if params.first().map(|p| p.value).unwrap_or(0) == 0 {
                    self.respond(b"\x1b[?62;22c"); // VT220-class, color support
                } else if params.first().map(|p| p.value) == Some(62) {
                    self.respond(b"\x1b[?62;22c");
                }
            }
            (false, None, b'n') => match param_or(params, 0, 0) {
                5 => self.respond(b"\x1b[0n"),
                6 => {
                    let (r, c) = (self.grid().cursor.row + 1, self.grid().cursor.col + 1);
                    self.respond(format!("\x1b[{r};{c}R").as_bytes());
                }
                _ => {}
            },
            // DECSTBM
            (false, None, b'r') => {
                if params.is_empty() {
                    // ESC[r → full screen.
                    self.grid_mut().set_region_to_full();
                    let g = self.grid_mut();
                    g.cursor.row = if g.origin_mode { g.region_top() } else { 0 };
                    g.cursor.col = 0;
                    g.wrap_next = false;
                } else {
                    let top = param_or(params, 0, 1).max(1) as usize;
                    let bot = param_or(params, 1, self.rows as u16).max(1) as usize;
                    if top < bot && bot <= self.rows {
                        if top == 1 && bot == self.rows {
                            self.grid_mut().set_region_to_full();
                        } else {
                            self.grid_mut().set_region(top - 1, bot - 1);
                        }
                        let g = self.grid_mut();
                        if g.origin_mode {
                            g.cursor.row = g.region_top();
                        } else {
                            g.cursor.row = 0;
                        }
                        g.cursor.col = 0;
                        g.wrap_next = false;
                    }
                }
            }
            // DECSC / DECRC
            (false, None, b's') => {
                let g = self.grid();
                self.saved = SavedCursor {
                    row: g.cursor.row,
                    col: g.cursor.col,
                    pen: self.pen.clone(),
                    origin: g.origin_mode,
                    charset_g: self.charset_shift,
                    wrap_next: g.wrap_next,
                };
            }
            (false, None, b'u') => {
                let s = self.saved.clone();
                let g = self.grid_mut();
                g.cursor.row = s.row.min(g.rows - 1);
                g.cursor.col = s.col.min(g.cols - 1);
                g.origin_mode = s.origin;
                g.wrap_next = s.wrap_next;
                self.pen = s.pen;
                self.charset_shift = s.charset_g;
            }
            // CBT — cursor backward tab
            (false, None, b'Z') => {
                for _ in 0..n(0, 1) {
                    self.grid_mut().tab_backward();
                }
            }
            // SGR
            (false, None, b'm') => self.sgr(params),
            // DECALN
            (false, Some(b'#'), b'8') => {
                let g = self.grid_mut();
                for cell in g.cells.iter_mut() {
                    *cell = Cell {
                        ch: 'E',
                        ..Cell::default()
                    };
                }
            }
            // DECSCUSR: 0/1 = blink, 2+ = steady
            (false, Some(b' '), b'q') => {
                let style = param_or(params, 0, 0);
                self.modes.cursor_blink = Some(matches!(style, 0 | 1));
            }
            // DECRQM (query mode): CSI ? Pm $ p
            (true, Some(b'$'), b'p') => {
                let m = param_or(params, 0, 0);
                let state = self.query_mode(m);
                self.respond(format!("\x1b[?{m};{state}$y").as_bytes());
            }
            // XTWINOPS
            (false, None, b't') => {
                if param_or(params, 0, 0) == 18 {
                    self.respond(format!("\x1b[8;{};{}t", self.rows, self.cols).as_bytes());
                }
            }
            // DECSET / DECRST
            (true, None, b'h') | (true, None, b'l') => {
                let set = final_byte == b'h';
                for p in params {
                    self.dec_private(p.value, set);
                }
            }
            // SM/RM (ANSI modes): IRM not implemented; ignore.
            (false, None, b'h') | (false, None, b'l') => {}
            _ => {}
        }
    }

    fn esc_dispatch(&mut self, intermediates: &[u8], final_byte: u8) {
        match (intermediates.first(), final_byte) {
            (None, b'7') => {
                // DECSC
                let g = self.grid();
                self.saved = SavedCursor {
                    row: g.cursor.row,
                    col: g.cursor.col,
                    pen: self.pen.clone(),
                    origin: g.origin_mode,
                    charset_g: self.charset_shift,
                    wrap_next: g.wrap_next,
                };
            }
            (None, b'8') => {
                let s = self.saved.clone();
                let g = self.grid_mut();
                g.cursor.row = s.row.min(g.rows - 1);
                g.cursor.col = s.col.min(g.cols - 1);
                g.origin_mode = s.origin;
                g.wrap_next = s.wrap_next;
                self.pen = s.pen;
                self.charset_shift = s.charset_g;
            }
            (None, b'D') => {
                // IND — like LF without CR
                let at_bottom = self.grid().cursor.row == self.grid().region_bottom();
                if at_bottom {
                    self.scroll_up_capture(1);
                } else {
                    self.grid_mut().move_down(1);
                }
            }
            (None, b'E') => {
                // NEL — CR + LF
                let g = self.grid_mut();
                g.cursor.col = 0;
                let at_bottom = self.grid().cursor.row == self.grid().region_bottom();
                if at_bottom {
                    self.scroll_up_capture(1);
                } else {
                    self.grid_mut().move_down(1);
                }
                self.grid_mut().wrap_next = false;
            }
            (None, b'M') => {
                // RI
                let at_top = self.grid().cursor.row == self.grid().region_top();
                if at_top {
                    self.grid_mut().scroll_down(1);
                } else {
                    self.grid_mut().move_up(1);
                }
            }
            (None, b'H') => self.grid_mut().set_tab(),
            (None, b'c') => {
                // RIS — full reset (scrollback kept, xterm/alacritty style)
                self.main_grid = Grid::new(self.cols, self.rows);
                self.alt_grid = Grid::new(self.cols, self.rows);
                self.modes = ModeFlags {
                    autowrap: true,
                    cursor_visible: true,
                    ..ModeFlags::default()
                };
                self.pen = Pen::default();
                self.charset_g0 = b'B';
                self.charset_g1 = b'B';
                self.charset_shift = 0;
                self.title.clear();
                self.palette_overrides.clear();
            }
            (None, b'=') => self.modes.app_keypad = true,
            (None, b'>') => self.modes.app_keypad = false,
            (Some(b'('), f) => self.charset_g0 = f,
            (Some(b')'), f) => self.charset_g1 = f,
            (Some(b'#'), b'8') => {
                for cell in self.grid_mut().cells.iter_mut() {
                    *cell = Cell {
                        ch: 'E',
                        ..Cell::default()
                    };
                }
            }
            _ => {}
        }
    }

    fn osc_dispatch(&mut self, params: &[&[u8]]) {
        if params.is_empty() {
            return;
        }
        let code = std::str::from_utf8(params[0]).unwrap_or("");
        match code {
            "0" | "2" => {
                if let Some(t) = params.get(1) {
                    self.title = String::from_utf8_lossy(t).into_owned();
                    self.events.push(EventKind::Title);
                }
            }
            "7" => {
                if let Some(p) = params.get(1) {
                    let s = String::from_utf8_lossy(p);
                    if let Some(idx) = s.find("file://") {
                        let path = &s[idx + 7..];
                        let path = path
                            .splitn(2, '/')
                            .skip(1)
                            .map(|rest| format!("/{rest}"))
                            .next()
                            .unwrap_or_else(|| "/".to_string());
                        let decoded = percent_decode(&path);
                        if decoded.starts_with('/') {
                            self.cwd = Some(decoded);
                            self.events.push(EventKind::CwdChanged);
                        }
                    }
                }
            }
            "4" => {
                // OSC 4 ; idx ; spec (query "?" or set)
                if let (Some(idx), Some(spec)) = (params.get(1), params.get(2)) {
                    let idx: usize = std::str::from_utf8(idx)
                        .ok()
                        .and_then(|s| s.parse().ok())
                        .unwrap_or(0);
                    if spec == b"?" {
                        let rgb = self.resolve_palette_index(idx as u8);
                        self.respond(
                            format!(
                                "\x1b]4;{idx};rgb:{:02x}{:02x}/{:02x}{:02x}/{:02x}{:02x}\x07",
                                (rgb >> 16) & 0xFF,
                                (rgb >> 16) & 0xFF,
                                (rgb >> 8) & 0xFF,
                                (rgb >> 8) & 0xFF,
                                rgb & 0xFF,
                                rgb & 0xFF
                            )
                            .as_bytes(),
                        );
                    } else {
                        let s = String::from_utf8_lossy(spec);
                        if let Some(Color::Rgb(v)) = Color::parse_hex(&s) {
                            if let Some(slot) = self
                                .palette_overrides
                                .iter_mut()
                                .find(|(i, _)| *i == idx as u8)
                            {
                                slot.1 = v;
                            } else {
                                self.palette_overrides.push((idx as u8, v));
                            }
                        }
                    }
                }
            }
            "10" | "11" => {
                let is_fg = code == "10";
                let spec = params.get(1);
                if let Some(spec) = spec {
                    if spec == b"?" {
                        let cur = if is_fg {
                            self.default_fg
                        } else {
                            self.default_bg
                        };
                        let rgb = match cur {
                            Color::Rgb(v) => v,
                            _ => {
                                if is_fg {
                                    0xE8E8E8
                                } else {
                                    0x0E1218
                                }
                            }
                        };
                        self.respond(
                            format!(
                                "\x1b]{};rgb:{:02x}{:02x}/{:02x}{:02x}/{:02x}{:02x}\x07",
                                code,
                                (rgb >> 16) & 0xFF,
                                (rgb >> 16) & 0xFF,
                                (rgb >> 8) & 0xFF,
                                (rgb >> 8) & 0xFF,
                                rgb & 0xFF,
                                rgb & 0xFF
                            )
                            .as_bytes(),
                        );
                    } else {
                        let s = String::from_utf8_lossy(spec);
                        if let Some(Color::Rgb(v)) = Color::parse_hex(&s) {
                            if is_fg {
                                self.default_fg = Color::Rgb(v);
                            } else {
                                self.default_bg = Color::Rgb(v);
                            }
                        }
                    }
                }
            }
            "52" => {
                // OSC 52 ; c ; base64
                if let Some(payload) = params.get(2) {
                    if let Ok(text) = base64_decode(payload) {
                        self.clipboard = Some(String::from_utf8_lossy(&text).into_owned());
                        self.events.push(EventKind::ClipboardSet);
                    }
                }
            }
            _ => {}
        }
    }

    fn hook(&mut self, _params: &[Param], _intermediates: &[u8], _final_byte: u8) {}
    fn put(&mut self, _byte: u8) {}
    fn unhook(&mut self) {}
}

impl Terminal {
    fn query_mode(&self, m: u16) -> u8 {
        // 0 = not recognized, 1 = set, 2 = reset
        let f = &self.modes;
        match m {
            1 => i8v(f.app_cursor),
            6 => i8v(f.origin),
            7 => i8v(f.autowrap),
            25 => i8v(f.cursor_visible),
            47 | 1047 | 1049 => i8v(f.alt_screen),
            66 => i8v(f.app_keypad),
            2004 => i8v(f.bracketed_paste),
            1004 => i8v(f.focus_events),
            1006 => i8v(f.mouse_sgr),
            _ => 0,
        }
    }

    fn dec_private(&mut self, mode: u16, set: bool) {
        let f = &mut self.modes;
        match mode {
            1 => f.app_cursor = set,
            5 => f.reverse_video = set,
            6 => {
                f.origin = set;
                let g = self.grid_mut();
                g.origin_mode = set;
                g.cursor.row = if set { g.region_top() } else { 0 };
                g.cursor.col = 0;
            }
            7 => f.autowrap = set,
            12 => f.cursor_blink = Some(set),
            25 => f.cursor_visible = set,
            47 | 1047 => {
                self.switch_alt(set);
            }
            1049 => {
                if set != f.alt_screen {
                    if set {
                        // Save main content + cursor, clear alt.
                        self.saved_main = Some((
                            self.main_grid.cells.clone(),
                            CursorState {
                                row: self.main_grid.cursor.row,
                                col: self.main_grid.cursor.col,
                                wrap_next: self.main_grid.wrap_next,
                                origin: self.main_grid.origin_mode,
                                region: self.main_grid.scroll_region,
                            },
                        ));
                        self.alt_grid = Grid::new(self.cols, self.rows);
                        f.alt_screen = true;
                    } else {
                        if let Some((cells, st)) = self.saved_main.take() {
                            self.main_grid.cells = cells;
                            self.main_grid.cursor.row = st.row.min(self.main_grid.rows - 1);
                            self.main_grid.cursor.col = st.col.min(self.main_grid.cols - 1);
                            self.main_grid.wrap_next = st.wrap_next;
                            self.main_grid.origin_mode = st.origin;
                            self.main_grid.scroll_region = st.region;
                        }
                        f.alt_screen = false;
                    }
                }
            }
            66 => f.app_keypad = set,
            1000 => f.mouse_protocol = if set { 1000 } else { 0 },
            1002 => f.mouse_protocol = if set { 1002 } else { 0 },
            1003 => f.mouse_protocol = if set { 1003 } else { 0 },
            1006 => f.mouse_sgr = set,
            1004 => f.focus_events = set,
            2004 => f.bracketed_paste = set,
            _ => {}
        }
    }

    fn switch_alt(&mut self, set: bool) {
        if self.modes.alt_screen == set {
            return;
        }
        self.modes.alt_screen = set;
    }

    fn sgr(&mut self, params: &[Param]) {
        if params.is_empty() {
            self.pen = Pen::default();
            return;
        }
        let mut i = 0;
        while i < params.len() {
            let v = params[i].value;
            let sub = &params[i].sub;
            match v {
                0 => self.pen = Pen::default(),
                1 => self.pen.attrs |= ATTR_BOLD,
                2 => self.pen.attrs |= ATTR_DIM,
                3 => self.pen.attrs |= ATTR_ITALIC,
                4 => {
                    // underline style with subparams (4:0 none, 4:1..)
                    if sub.is_empty() {
                        self.pen.attrs |= ATTR_UNDERLINE;
                    } else if sub.first() == Some(&0) {
                        self.pen.attrs &= !ATTR_UNDERLINE;
                    } else {
                        self.pen.attrs |= ATTR_UNDERLINE;
                    }
                }
                5 => self.pen.attrs |= 1 << 10, // blink
                7 => self.pen.attrs |= ATTR_REVERSE,
                8 => self.pen.attrs |= ATTR_INVISIBLE,
                9 => self.pen.attrs |= ATTR_STRIKE,
                21 => self.pen.attrs |= ATTR_UNDERLINE,
                22 => self.pen.attrs &= !(ATTR_BOLD | ATTR_DIM),
                23 => self.pen.attrs &= !ATTR_ITALIC,
                24 => self.pen.attrs &= !ATTR_UNDERLINE,
                25 => self.pen.attrs &= !(1 << 10),
                27 => self.pen.attrs &= !ATTR_REVERSE,
                28 => self.pen.attrs &= !ATTR_INVISIBLE,
                29 => self.pen.attrs &= !ATTR_STRIKE,
                30..=37 => self.pen.fg = Color::Indexed((v - 30) as u8),
                38 => {
                    self.pen.fg = extended_color(params, sub, &mut i);
                }
                39 => self.pen.fg = Color::Default,
                40..=47 => self.pen.bg = Color::Indexed((v - 40) as u8),
                48 => {
                    self.pen.bg = extended_color(params, sub, &mut i);
                }
                49 => self.pen.bg = Color::Default,
                90..=97 => self.pen.fg = Color::Indexed((v - 90 + 8) as u8),
                100..=107 => self.pen.bg = Color::Indexed((v - 100 + 8) as u8),
                _ => {}
            }
            i += 1;
        }
    }

    fn resolve_palette_index(&self, idx: u8) -> u32 {
        if let Some((_, v)) = self.palette_overrides.iter().find(|(i, _)| *i == idx) {
            return *v;
        }
        if idx < 16 {
            Scheme::alpine_dark().palette[idx as usize]
        } else {
            Scheme::extended_index(idx)
        }
    }
}

fn i8v(b: bool) -> u8 {
    if b {
        1
    } else {
        2
    }
}

fn extended_color(params: &[Param], sub: &[u16], i: &mut usize) -> Color {
    let mode = if !sub.is_empty() {
        sub.first().copied().unwrap_or(0)
    } else {
        params.get(*i + 1).map(|p| p.value).unwrap_or(0)
    };
    let idx_off = if !sub.is_empty() { 0 } else { 1 };
    match mode {
        5 => {
            let idx = if !sub.is_empty() {
                sub.get(1).copied().unwrap_or(0)
            } else {
                params.get(*i + 2).map(|p| p.value).unwrap_or(0)
            };
            *i += idx_off + 1;
            Color::Indexed(idx.min(255) as u8)
        }
        2 => {
            let (r, g, b) = if !sub.is_empty() {
                (
                    sub.get(1).copied().unwrap_or(0),
                    sub.get(2).copied().unwrap_or(0),
                    sub.get(3).copied().unwrap_or(0),
                )
            } else {
                (
                    params.get(*i + 2).map(|p| p.value).unwrap_or(0),
                    params.get(*i + 3).map(|p| p.value).unwrap_or(0),
                    params.get(*i + 4).map(|p| p.value).unwrap_or(0),
                )
            };
            *i += idx_off + 3;
            Color::Rgb(((r.min(255) as u32) << 16) | ((g.min(255) as u32) << 8) | b.min(255) as u32)
        }
        _ => Color::Default,
    }
}

fn percent_decode(s: &str) -> String {
    let b = s.as_bytes();
    let mut out = Vec::with_capacity(b.len());
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            let hex = std::str::from_utf8(&b[i + 1..i + 3]).unwrap_or("");
            if let Ok(v) = u8::from_str_radix(hex, 16) {
                out.push(v);
                i += 3;
                continue;
            }
        }
        out.push(b[i]);
        i += 1;
    }
    String::from_utf8_lossy(&out).into_owned()
}

fn base64_decode(s: &[u8]) -> Result<Vec<u8>, ()> {
    const TBL: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut acc: u32 = 0;
    let mut bits = 0;
    let mut out = Vec::new();
    for &c in s {
        if c == b'=' || c == b'\n' || c == b'\r' {
            continue;
        }
        let v = TBL.iter().position(|&t| t == c).ok_or(())? as u32;
        acc = (acc << 6) | v;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((acc >> bits) as u8);
        }
    }
    Ok(out)
}

